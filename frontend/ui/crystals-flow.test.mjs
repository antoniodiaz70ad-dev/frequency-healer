import assert from 'node:assert/strict';
import test from 'node:test';
import { chromium } from 'playwright-core';
import { startLocalServer } from '../scripts/local-test-server.mjs';

test('crystals: prepare, play, pause, save, reload, follow-up and portable export', { timeout: 60000 }, async () => {
  const server = await startLocalServer(false);
  let browser;
  try {
    browser = await chromium.launch({ headless: true, timeout: 15000, ...(process.env.FH_UI_BROWSER_PATH ? { executablePath: process.env.FH_UI_BROWSER_PATH } : process.env.FH_UI_BROWSER === 'chromium' ? {} : { channel: 'chrome' }), args: ['--no-sandbox', '--mute-audio', '--disable-audio-output'] });
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, acceptDownloads: true });
    const page = await context.newPage(); page.setDefaultTimeout(8000);
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(server.origin + '/preparacion-cristales');
    await page.getByRole('heading', { name: 'Preparación de cristales', exact: true }).waitFor();
    await page.getByLabel('Nombre de mi cristal').fill('Mi cuarzo');
    await page.getByRole('combobox', { name: 'Recorrido', exact: true }).selectOption('10');
    await page.getByRole('button', { name: 'Usar frase de partida' }).click();
    await page.getByLabel('Escena que representa mi intención').fill('Una conversación clara');
    await page.getByRole('button', { name: 'Guardar preparación', exact: true }).click();
    await page.getByText('Preparación guardada en este navegador.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Revisar sonido y comenzar' }).click();
    await page.getByRole('spinbutton', { name: 'Tono base (Hz)', exact: true }).fill('0');
    assert.equal(await page.getByRole('button', { name: 'Comenzar preparación' }).isEnabled(), false);
    await page.getByRole('spinbutton', { name: 'Tono base (Hz)', exact: true }).fill('256');
    await page.getByLabel('Leer instrucciones con voz', { exact: true }).check();
    await page.getByRole('combobox', { name: 'Salida de sonido', exact: true }).selectOption('coils');
    assert.equal(await page.getByLabel('Leer instrucciones con voz', { exact: true }).isEnabled(), false);
    assert.equal(await page.getByLabel('Leer instrucciones con voz', { exact: true }).isChecked(), false);
    await page.getByRole('button', { name: 'Comenzar preparación' }).click();
    await page.getByRole('button', { name: 'Pausar', exact: true }).waitFor();
    await page.waitForTimeout(700);
    await page.getByRole('button', { name: 'Pausar', exact: true }).click();
    const remaining = await page.getByLabel('Tiempo restante').textContent();
    await page.waitForTimeout(350);
    assert.equal(await page.getByLabel('Tiempo restante').textContent(), remaining);
    await page.getByRole('button', { name: 'Reanudar', exact: true }).click();
    await page.getByRole('button', { name: 'Pausar', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Detener', exact: true }).click();
    await page.getByLabel('Lo que observé o sentí').fill('Experiencia sintética');
    await page.getByRole('button', { name: 'Guardar sesión en el cuaderno' }).click();
    await page.getByRole('button', { name: 'Mi cuaderno', exact: true }).click();
    await page.locator('details').filter({ has: page.locator('summary', { hasText: 'Mi cuarzo' }) }).locator('summary').click();
    await page.getByLabel('Observación posterior', { exact: true }).fill('Revisión posterior');
    await page.getByRole('button', { name: 'Guardar observación', exact: true }).click();
    const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('fh.crystals.v1')));
    assert.equal(stored.sessions.length, 1); assert.equal(stored.sessions[0].status, 'stopped');
    assert.equal(stored.sessions[0].preparation.baseHz, 256); assert.equal(stored.sessions[0].preparation.exposure, 'coils'); assert.equal(stored.sessions[0].followUps[0].text, 'Revisión posterior');
    const downloadPending = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Exportar cuaderno', exact: true }).click();
    const download = await downloadPending; assert.equal(download.suggestedFilename(), 'resonance-lab-cristales.json');
    const second = await browser.newContext(); const other = await second.newPage();
    await other.goto(server.origin + '/preparacion-cristales');
    await other.getByRole('button', { name: 'Mi cuaderno', exact: true }).click();
    await other.getByLabel('Importar cuaderno', { exact: true }).setInputFiles({ name: 'cuaderno.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(stored)) });
    await other.getByText('Cuaderno importado. Las sesiones existentes se conservaron.', { exact: true }).waitFor();
    assert.deepEqual(await other.evaluate(() => JSON.parse(localStorage.getItem('fh.crystals.v1'))), stored);
    await second.close();
    await page.reload(); await page.getByRole('button', { name: 'Mi cuaderno', exact: true }).click();
    await page.getByRole('heading', { name: 'Mi cuaderno · 1 sesiones' }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    assert.deepEqual(errors, []);
    await context.close();
  } finally { await browser?.close(); await server.close(); }
});
